<#
.SYNOPSIS
    Rebuilds the generated tables in README.md and Docs/design/README.md, so they can't drift.

.DESCRIPTION
    Rewrites the text between these marker pairs:
        README.md:             <!-- GENERATED:tools -->   the ToolCore blocks, read from Content/Data/CubeBlocks_GVK_Tools.sbc
        Docs/design/README.md: <!-- GENERATED:design-docs -->   from each design doc's front matter
    Everything outside the markers is left alone. It also reports a block in the SBC file that the README
    does not know how to describe.

.PARAMETER Check
    Report whether the generated text is out of date without writing it (exit code 1 if it is).
#>
[CmdletBinding()]
param([switch]$Check)

$ErrorActionPreference = 'Stop'
$root = Split-Path -Parent $PSScriptRoot
$readmePath = Join-Path $root 'README.md'
$indexPath = Join-Path $root 'Docs\design\README.md'
$problems = @()

# --- Tools table: every GVK_* definition in the SBC file ---------------------------------------
$sbc = [IO.File]::ReadAllText((Join-Path $root 'Content\Data\CubeBlocks_GVK_Tools.sbc'))
$toolRows = foreach ($m in [regex]::Matches($sbc, '(?s)<Definition\b.*?</Definition>')) {
    $block = $m.Value
    $sub = [regex]::Match($block, '<SubtypeId>(GVK_[A-Za-z0-9_]+)</SubtypeId>').Groups[1].Value
    if (-not $sub) { continue }
    $kind = switch -Regex ($sub) {
        'Salvage' { 'Salvage Beam Turret'; break }
        'Welder' { 'Ship welder'; break }
        'Grinder' { 'Ship grinder'; break }
        'Prototech.*Drill' { 'Advanced Ship Drill'; break }
        'Drill' { 'Ship drill'; break }
        default { $script:problems += "$sub is not a welder, grinder, drill or turret: describe it in tools/Update-Readme.ps1"; 'Other' }
    }
    $own = [regex]::Match($block, '<AffectOwnGrid>(\w+)</AffectOwnGrid>').Groups[1].Value
    $ownText = switch ($own) { 'true' { 'Yes' } 'false' { 'No' } default { 'n/a' } }
    $size = if ($sub -match 'Small') { 'Small grid' } elseif ($sub -match 'Large') { 'Large grid' } else { '-' }
    $skin = if ($sub -match 'Reskin$') { 'reskin' } else { 'standard' }
    [pscustomobject]@{ Kind = $kind; Sub = $sub; Size = $size; Skin = $skin; Own = $ownText }
}
$toolLines = @('| Tool | Subtype | Grid | Version | Affects its own grid |', '| --- | --- | --- | --- | --- |')
foreach ($r in $toolRows | Sort-Object Kind, Sub) { $toolLines += "| $($r.Kind) | ``$($r.Sub)`` | $($r.Size) | $($r.Skin) | $($r.Own) |" }

# --- Design doc index -----------------------------------------------------------------------
$indexLines = @('| Doc | Covered files | Checked |', '| --- | --- | --- |')
foreach ($doc in Get-ChildItem (Join-Path $root 'Docs\design') -Filter *.md | Where-Object { $_.Name -ne 'README.md' } | Sort-Object Name) {
    $fm = [regex]::Match([IO.File]::ReadAllText($doc.FullName), '(?s)\A---\r?\n(.*?)\r?\n---')
    if (-not $fm.Success) { $problems += "$($doc.Name) has no front matter"; continue }
    $title = [regex]::Match($fm.Groups[1].Value, '(?m)^title:\s*(.+?)\s*$').Groups[1].Value
    $covers = ([regex]::Matches($fm.Groups[1].Value, '(?m)^  - .+$')).Count
    $checked = [regex]::Match($fm.Groups[1].Value, '(?m)^checked:\s*(\S+)').Groups[1].Value
    $indexLines += "| [$title]($($doc.Name)) | $covers | $(if ($checked) { $checked } else { '-' }) |"
}

function Set-Block([string]$text, [string]$key, [string]$source, [string[]]$lines, [string]$nl) {
    $pattern = "(?s)(<!-- GENERATED:$key -->).*?(<!-- /GENERATED:$key -->)"
    if ($text -notmatch $pattern) { $script:problems += "missing GENERATED:$key markers"; return $text }
    $block = $nl + '<!-- Generated by tools/Update-Readme.ps1 from ' + $source + '. Do not edit by hand. -->' + $nl +
        '*Generated by `tools/Update-Readme.ps1` from ' + $source + '. To change it, edit the source.*' + $nl + $nl + ($lines -join $nl) + $nl
    [regex]::Replace($text, $pattern, { param($m) $m.Groups[1].Value + $block + $m.Groups[2].Value })
}
$readme = [IO.File]::ReadAllText($readmePath)
$nl = if ($readme.Contains("`r`n")) { "`r`n" } else { "`n" }
$newReadme = Set-Block $readme 'tools' 'the SBC file' $toolLines $nl
$index = [IO.File]::ReadAllText($indexPath)
$newIndex = Set-Block $index 'design-docs' 'the design docs' $indexLines $nl

foreach ($p in $problems) { Write-Warning $p }
$stale = ($newReadme -cne $readme) -or ($newIndex -cne $index)
if ($Check) {
    if ($stale) { Write-Output 'Generated docs are out of date.' }
    if ($stale -or $problems.Count) { exit 1 }
    Write-Output 'Generated docs are up to date.'; exit 0
}
if ($stale) {
    $utf8 = New-Object Text.UTF8Encoding($false)
    [IO.File]::WriteAllText($readmePath, $newReadme, $utf8)
    [IO.File]::WriteAllText($indexPath, $newIndex, $utf8)
    Write-Output 'Generated docs regenerated.'
} else { Write-Output 'Generated docs are up to date.' }
if ($problems.Count) { exit 1 }
